export type Look = { kind: 'flag' | 'icon' | 'emoji'; value: string } | null;

export function parseLook(v: string | null | undefined): Look {
  if (!v) return null;
  const at = v.indexOf(':');
  if (at < 0) return { kind: 'flag', value: v };
  const kind = v.slice(0, at);
  const value = v.slice(at + 1);
  return kind === 'flag' || kind === 'icon' || kind === 'emoji' ? { kind, value } : null;
}

/** Name of a look for labels: country name, icon name or the emoji itself. */
export function lookName(
  v: string,
  locale: 'ru' | 'en',
  flagName: (c: string, l: 'ru' | 'en') => string
): string {
  const l = parseLook(v);
  if (!l) return v;
  if (l.kind === 'flag') return flagName(l.value, locale);
  if (l.kind === 'emoji') return l.value;
  const words = ICON_BY_ID.get(l.value)?.words.split(' ') ?? [];
  const name = locale === 'ru' ? (words[1] ?? l.value) : l.value.replace(/-/g, ' ');
  return name.charAt(0).toUpperCase() + name.slice(1);
}

const has = (q: string, words: string) => words.toLowerCase().includes(q.trim().toLowerCase());
export const searchIcons = (q: string): string[] =>
  ICONS.filter((x) => !q.trim() || has(q, x.words)).map((x) => 'icon:' + x.id);
export const searchEmoji = (q: string): string[] =>
  EMOJI.filter(([, w]) => !q.trim() || has(q, w)).map(([e]) => 'emoji:' + e);
